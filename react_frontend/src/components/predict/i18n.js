/** t('vi', 'sectionOf', { i: 1, n: 4 }) -> "Phần 1/4" */
export const t = (lang, key, params = {}) => {
  const s = STRINGS[lang]?.[key] ?? STRINGS.vi[key] ?? key;
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
};

/** Lấy nhãn theo ngôn ngữ từ object { vi, en } */
export const pick = (obj, lang) => (obj && typeof obj === 'object' ? obj[lang] ?? obj.vi : obj);